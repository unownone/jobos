"""Token-burn and latency metrics. Same Postgres as the job board."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from app.sql import SqlConnection
from app.tenant import account_id_of

SCHEMA = """
CREATE TABLE IF NOT EXISTS token_burn (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id TEXT NOT NULL DEFAULT 'acc_compat',
    ts TEXT NOT NULL,
    tool_name TEXT NOT NULL,
    skill TEXT,
    lane TEXT,
    prompt_tokens INTEGER NOT NULL DEFAULT 0,
    completion_tokens INTEGER NOT NULL DEFAULT 0,
    total_tokens INTEGER NOT NULL DEFAULT 0,
    cost_usd REAL,
    duration_ms REAL,
    job_id TEXT,
    actor_role TEXT,
    actor TEXT,
    extra_json TEXT
);
CREATE INDEX IF NOT EXISTS idx_burn_tool ON token_burn(tool_name);
CREATE INDEX IF NOT EXISTS idx_burn_skill ON token_burn(skill);
CREATE INDEX IF NOT EXISTS idx_burn_ts ON token_burn(ts);
"""


def utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def percentile(values: list[float], p: float) -> float | None:
    if not values:
        return None
    ordered = sorted(values)
    if len(ordered) == 1:
        return ordered[0]
    rank = (p / 100.0) * (len(ordered) - 1)
    low = int(rank)
    high = min(low + 1, len(ordered) - 1)
    frac = rank - low
    return ordered[low] * (1 - frac) + ordered[high] * frac


class MetricsStore:
    def __init__(self, conn: SqlConnection, jsonl_path: Path | None = None) -> None:
        self.conn = conn
        self.jsonl_path = jsonl_path
        self.conn.executescript(SCHEMA)
        self.conn.commit()

    def close(self) -> None:
        return None

    def record_token_burn(self, row: dict[str, Any]) -> dict[str, Any]:
        ts = row.get("timestamp") or utc_now()
        prompt = int(row.get("prompt_tokens") or 0)
        completion = int(row.get("completion_tokens") or 0)
        total = row.get("total_tokens")
        total_i = int(total) if total is not None else prompt + completion
        skill = str(row.get("skill") or row.get("lane") or "")
        lane = str(row.get("lane") or row.get("skill") or "")
        stored = {
            "ts": ts,
            "tool_name": str(row["tool_name"]),
            "skill": skill,
            "lane": lane,
            "prompt_tokens": prompt,
            "completion_tokens": completion,
            "total_tokens": total_i,
            "cost_usd": row.get("cost_usd"),
            "duration_ms": row.get("duration_ms"),
            "job_id": row.get("job_id") or "",
            "actor_role": row.get("actor_role") or "",
            "actor": row.get("actor") or "",
            "extra": row.get("extra") or {},
        }
        cur = self.conn.execute(
            """
            INSERT INTO token_burn (
                account_id, ts, tool_name, skill, lane, prompt_tokens, completion_tokens, total_tokens,
                cost_usd, duration_ms, job_id, actor_role, actor, extra_json
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                account_id_of(row),
                stored["ts"],
                stored["tool_name"],
                stored["skill"],
                stored["lane"],
                stored["prompt_tokens"],
                stored["completion_tokens"],
                stored["total_tokens"],
                stored["cost_usd"],
                stored["duration_ms"],
                stored["job_id"],
                stored["actor_role"],
                stored["actor"],
                json.dumps(stored["extra"], ensure_ascii=False) if stored["extra"] else None,
            ),
        )
        self.conn.commit()
        stored["id"] = cur.lastrowid
        if self.jsonl_path is not None:
            self.jsonl_path.parent.mkdir(parents=True, exist_ok=True)
            with self.jsonl_path.open("a", encoding="utf-8") as fh:
                fh.write(json.dumps(stored, ensure_ascii=False) + "\n")
        return stored

    def list_burns(self, limit: int = 100, *, tenant: Any | None = None) -> list[dict[str, Any]]:
        limit = max(1, min(limit, 1000))
        cur = self.conn.execute(
            "SELECT * FROM token_burn WHERE account_id = ? ORDER BY id DESC LIMIT ?",
            (account_id_of(tenant), limit),
        )
        return [self._row(r) for r in cur.fetchall()]

    def summary(self, *, tenant: Any | None = None) -> dict[str, Any]:
        cur = self.conn.execute(_SUMMARY_SQL, (account_id_of(tenant),))
        total: dict[str, Any] | None = None
        grouped: dict[str, list[dict[str, Any]]] = {"tool": [], "skill": [], "role": []}
        for row in cur.fetchall():
            bucket = str(row["bucket"])
            if bucket == "total":
                total = dict(row)
                continue
            grouped.setdefault(bucket, []).append(dict(row))
        if total is None:
            total = {
                "n": 0,
                "prompt_tokens": 0,
                "completion_tokens": 0,
                "total_tokens": 0,
                "cost_usd": 0,
                "duration_ms_p50": None,
                "duration_ms_p95": None,
                "n_with_duration": 0,
            }
        return {
            "n": int(total["n"] or 0),
            "totals": _totals_from_agg(total),
            "by_tool": _pack_groups(grouped.get("tool", [])),
            "by_skill": _pack_groups(grouped.get("skill", [])),
            "by_role": _pack_groups(grouped.get("role", [])),
        }

    def _row(self, row: Any) -> dict[str, Any]:
        extra = {}
        raw = row["extra_json"]
        if raw:
            extra = json.loads(raw)
        return {
            "id": row["id"],
            "ts": row["ts"],
            "tool_name": row["tool_name"],
            "skill": row["skill"] or "",
            "lane": row["lane"] or "",
            "prompt_tokens": row["prompt_tokens"],
            "completion_tokens": row["completion_tokens"],
            "total_tokens": row["total_tokens"],
            "cost_usd": row["cost_usd"],
            "duration_ms": row["duration_ms"],
            "job_id": row["job_id"] or "",
            "actor_role": row["actor_role"] or "",
            "actor": row["actor"] or "",
            "extra": extra,
        }


_AGG_COLUMNS = """
    COUNT(*)::bigint AS n,
    COALESCE(SUM(prompt_tokens), 0)::bigint AS prompt_tokens,
    COALESCE(SUM(completion_tokens), 0)::bigint AS completion_tokens,
    COALESCE(SUM(total_tokens), 0)::bigint AS total_tokens,
    ROUND(COALESCE(SUM(cost_usd), 0)::numeric, 6) AS cost_usd,
    percentile_cont(0.5) WITHIN GROUP (ORDER BY duration_ms) AS duration_ms_p50,
    percentile_cont(0.95) WITHIN GROUP (ORDER BY duration_ms) AS duration_ms_p95,
    COUNT(duration_ms)::bigint AS n_with_duration
"""

_SUMMARY_SQL = f"""
WITH filtered AS (
    SELECT tool_name, skill, actor_role, prompt_tokens, completion_tokens,
           total_tokens, cost_usd, duration_ms
    FROM token_burn
    WHERE account_id = ?
)
SELECT bucket, name, n, prompt_tokens, completion_tokens, total_tokens, cost_usd,
       duration_ms_p50, duration_ms_p95, n_with_duration
FROM (
    SELECT 'total' AS bucket, '' AS name, {_AGG_COLUMNS}
    FROM filtered
    UNION ALL
    SELECT 'tool', COALESCE(NULLIF(tool_name, ''), '(none)'), {_AGG_COLUMNS}
    FROM filtered
    GROUP BY 2
    UNION ALL
    SELECT 'skill', COALESCE(NULLIF(skill, ''), '(none)'), {_AGG_COLUMNS}
    FROM filtered
    GROUP BY 2
    UNION ALL
    SELECT 'role', COALESCE(NULLIF(actor_role, ''), '(none)'), {_AGG_COLUMNS}
    FROM filtered
    GROUP BY 2
) agg
"""


def _totals_from_agg(row: dict[str, Any]) -> dict[str, Any]:
    p50 = row.get("duration_ms_p50")
    p95 = row.get("duration_ms_p95")
    return {
        "prompt_tokens": int(row.get("prompt_tokens") or 0),
        "completion_tokens": int(row.get("completion_tokens") or 0),
        "total_tokens": int(row.get("total_tokens") or 0),
        "cost_usd": round(float(row.get("cost_usd") or 0), 6),
        "duration_ms_p50": None if p50 is None else float(p50),
        "duration_ms_p95": None if p95 is None else float(p95),
        "n_with_duration": int(row.get("n_with_duration") or 0),
    }


def _pack_groups(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    packed = [{"name": str(row.get("name") or "(none)"), "n": int(row["n"]), **_totals_from_agg(row)} for row in rows]
    packed.sort(key=lambda item: (-int(item["total_tokens"]), str(item["name"])))
    return packed
