package store

const schemaSQL = `
CREATE TABLE IF NOT EXISTS accounts (
    id TEXT PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS users (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL,
    kind TEXT NOT NULL,
    track TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    password_hash TEXT NOT NULL DEFAULT '',
    display_name TEXT NOT NULL DEFAULT '',
    metadata_json TEXT NOT NULL DEFAULT '{}',
    created_by TEXT NOT NULL DEFAULT '',
    disabled_at TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL,
    user_id TEXT NOT NULL,
    token_hash TEXT NOT NULL UNIQUE,
    csrf_hash TEXT NOT NULL DEFAULT '',
    expires_at TEXT NOT NULL,
    last_seen TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS api_keys (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL,
    user_id TEXT NOT NULL,
    prefix TEXT NOT NULL,
    key_hash TEXT NOT NULL UNIQUE,
    created_at TEXT NOT NULL,
    revoked_at TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS invites (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL,
    track TEXT NOT NULL,
    mode TEXT NOT NULL,
    secret_hash TEXT NOT NULL,
    max_redemptions INTEGER NOT NULL,
    redemptions INTEGER NOT NULL DEFAULT 0,
    expires_at TEXT NOT NULL,
    revoked_at TEXT NOT NULL DEFAULT '',
    created_by TEXT NOT NULL DEFAULT '',
    allow_multiple_owners BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS jobs (
    account_id TEXT NOT NULL,
    id TEXT NOT NULL,
    company TEXT NOT NULL,
    title TEXT NOT NULL,
    location TEXT NOT NULL DEFAULT '',
    remote TEXT NOT NULL DEFAULT '',
    url TEXT NOT NULL DEFAULT '',
    apply_url TEXT NOT NULL DEFAULT '',
    apply_kind TEXT NOT NULL DEFAULT '',
    ats TEXT NOT NULL DEFAULT '',
    req_id TEXT NOT NULL DEFAULT '',
    sources_json TEXT NOT NULL DEFAULT '[]',
    status TEXT NOT NULL,
    score DOUBLE PRECISION,
    owners_json TEXT NOT NULL DEFAULT '{}',
    apply_packet_json TEXT NOT NULL DEFAULT '{}',
    outreach_packet_json TEXT NOT NULL DEFAULT '{}',
    research_json TEXT NOT NULL DEFAULT '{}',
    proof_json TEXT NOT NULL DEFAULT '{}',
    notes TEXT NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',
    expectations TEXT NOT NULL DEFAULT '',
    pay TEXT NOT NULL DEFAULT '',
    posted_at TEXT NOT NULL DEFAULT '',
    rejection_json TEXT NOT NULL DEFAULT '{}',
    conflicts_json TEXT NOT NULL DEFAULT '[]',
    stopped BOOLEAN NOT NULL DEFAULT FALSE,
    stop_reason TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    created_by_role TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (account_id, id)
);
CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id TEXT NOT NULL,
    ts TEXT NOT NULL,
    job_id TEXT NOT NULL DEFAULT '',
    actor_role TEXT NOT NULL,
    actor TEXT NOT NULL DEFAULT '',
    action TEXT NOT NULL,
    from_status TEXT NOT NULL DEFAULT '',
    to_status TEXT NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT '',
    fields_json TEXT NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS queue_items (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL,
    kind TEXT NOT NULL,
    track TEXT NOT NULL DEFAULT '',
    job_id TEXT NOT NULL DEFAULT '',
    payload_json TEXT NOT NULL DEFAULT '{}',
    status TEXT NOT NULL,
    claimed_by TEXT NOT NULL DEFAULT '',
    lease_until TEXT NOT NULL DEFAULT '',
    attempts INTEGER NOT NULL DEFAULT 0,
    dedupe_key TEXT NOT NULL,
    created_at TEXT NOT NULL,
    UNIQUE (account_id, dedupe_key)
);
CREATE TABLE IF NOT EXISTS people (
    account_id TEXT NOT NULL,
    id TEXT NOT NULL,
    name TEXT NOT NULL,
    title TEXT NOT NULL DEFAULT '',
    company TEXT NOT NULL DEFAULT '',
    job_id TEXT NOT NULL DEFAULT '',
    linkedin_url TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    email_confidence TEXT NOT NULL DEFAULT '',
    do_not_contact BOOLEAN NOT NULL DEFAULT FALSE,
    touches_json TEXT NOT NULL DEFAULT '[]',
    notes TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    PRIMARY KEY (account_id, id)
);
CREATE TABLE IF NOT EXISTS memory_items (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL,
    pod TEXT NOT NULL,
    kind TEXT NOT NULL,
    body TEXT NOT NULL,
    content_hash TEXT NOT NULL DEFAULT '',
    importance TEXT NOT NULL DEFAULT '',
    expires_at TEXT NOT NULL DEFAULT '',
    solidify_status TEXT NOT NULL DEFAULT 'none',
    created_by TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS messages (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL,
    from_user_id TEXT NOT NULL,
    to_user_id TEXT NOT NULL DEFAULT '',
    to_track TEXT NOT NULL DEFAULT '',
    job_id TEXT NOT NULL DEFAULT '',
    type TEXT NOT NULL,
    body TEXT NOT NULL,
    created_at TEXT NOT NULL,
    read_at TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS skills (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL DEFAULT '',
    slug TEXT NOT NULL,
    name TEXT NOT NULL,
    kind TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT '',
    tags_json TEXT NOT NULL DEFAULT '[]',
    scope TEXT NOT NULL,
    owner_user_id TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL,
    platform TEXT NOT NULL DEFAULT '',
    body TEXT NOT NULL DEFAULT '',
    origin TEXT NOT NULL DEFAULT '',
    version INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS skill_recordings (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL,
    skill_id TEXT NOT NULL,
    submitter_user_id TEXT NOT NULL,
    origin TEXT NOT NULL DEFAULT '',
    body TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL,
    proctor_note TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS presence (
    account_id TEXT NOT NULL,
    user_id TEXT NOT NULL,
    status TEXT NOT NULL,
    task_id TEXT NOT NULL DEFAULT '',
    last_heartbeat TEXT NOT NULL,
    user_agent TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (account_id, user_id)
);
CREATE TABLE IF NOT EXISTS token_burn (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id TEXT NOT NULL,
    ts TEXT NOT NULL,
    tool_name TEXT NOT NULL,
    skill TEXT NOT NULL DEFAULT '',
    lane TEXT NOT NULL DEFAULT '',
    prompt_tokens INTEGER NOT NULL DEFAULT 0,
    completion_tokens INTEGER NOT NULL DEFAULT 0,
    total_tokens INTEGER NOT NULL DEFAULT 0,
    cost_usd DOUBLE PRECISION NOT NULL DEFAULT 0,
    job_id TEXT NOT NULL DEFAULT '',
    actor_role TEXT NOT NULL DEFAULT '',
    actor TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS a2a_peers (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL,
    name TEXT NOT NULL,
    url TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS a2a_tasks (
    id TEXT PRIMARY KEY,
    account_id TEXT NOT NULL,
    track TEXT NOT NULL DEFAULT '',
    state TEXT NOT NULL,
    payload_json TEXT NOT NULL DEFAULT '{}',
    created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS hub_kv (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
`
