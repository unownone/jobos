"""Generate or rotate per-role hunt-board tokens.

Writes gitignored `board/.env` (and `board/tokens.local.json`).
Never prints existing tokens unless `--print` is passed.
Do not commit the output files. Do not paste tokens into the repo or group chats.
"""

from __future__ import annotations

import argparse
import json
import secrets
import sys
from pathlib import Path

ROLES = ("discovery", "apply", "outreach", "admin", "maintenance")
TOKEN_ENV = {
    "discovery": "BOARD_TOKEN_DISCOVERY",
    "apply": "BOARD_TOKEN_APPLY",
    "outreach": "BOARD_TOKEN_OUTREACH",
    "admin": "BOARD_TOKEN_ADMIN",
    "maintenance": "BOARD_TOKEN_MAINTENANCE",
}


def parse_env_file(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if not path.is_file():
        return out
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        out[key.strip()] = value.strip().strip('"').strip("'")
    return out


def new_token() -> str:
    return secrets.token_urlsafe(32)


def write_files(board_dir: Path, values: dict[str, str], tokens: dict[str, str]) -> None:
    board_dir.mkdir(parents=True, exist_ok=True)
    env_path = board_dir / ".env"
    json_path = board_dir / "tokens.local.json"
    lines = [
        "# Generated by scripts/board_gen_tokens.py — DO NOT COMMIT",
        f"BOARD_HOST={values.get('BOARD_HOST', '0.0.0.0')}",
        f"BOARD_PORT={values.get('BOARD_PORT', '8787')}",
        f"BOARD_DB={values.get('BOARD_DB', 'data/board.db')}",
    ]
    for role in ROLES:
        lines.append(f"{TOKEN_ENV[role]}={tokens[role]}")
    env_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    json_path.write_text(json.dumps(tokens, indent=2) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate gitignored hunt-board role tokens")
    parser.add_argument(
        "--dir",
        default=str(Path(__file__).resolve().parents[1] / "board"),
        help="board directory (default: repo board/)",
    )
    parser.add_argument(
        "--rotate",
        metavar="ROLE",
        choices=ROLES,
        help="regenerate one role token",
    )
    parser.add_argument("--rotate-all", action="store_true", help="regenerate every role token")
    parser.add_argument(
        "--print",
        action="store_true",
        dest="print_tokens",
        help="print tokens to stdout (maintainer issuance only)",
    )
    args = parser.parse_args()
    board_dir = Path(args.dir).resolve()
    env_path = board_dir / ".env"
    json_path = board_dir / "tokens.local.json"

    values = parse_env_file(env_path)
    existing: dict[str, str] = {}
    if json_path.is_file():
        payload = json.loads(json_path.read_text(encoding="utf-8"))
        if isinstance(payload, dict):
            for role in ROLES:
                if payload.get(role):
                    existing[role] = str(payload[role])
    for role in ROLES:
        env_name = TOKEN_ENV[role]
        if values.get(env_name):
            existing[role] = values[env_name]

    if args.rotate_all:
        targets = set(ROLES)
    elif args.rotate:
        targets = {args.rotate}
    else:
        targets = {role for role in ROLES if not existing.get(role)}

    tokens: dict[str, str] = {}
    created: list[str] = []
    rotated: list[str] = []
    for role in ROLES:
        if role in targets:
            tokens[role] = new_token()
            if existing.get(role):
                rotated.append(role)
            else:
                created.append(role)
        else:
            tokens[role] = existing[role]

    write_files(board_dir, values, tokens)

    print(f"wrote {env_path} and {json_path} (gitignored)", file=sys.stderr)
    if created:
        print("generated: " + ", ".join(created), file=sys.stderr)
    if rotated:
        print("rotated: " + ", ".join(rotated), file=sys.stderr)
    if not created and not rotated and not args.print_tokens:
        print("tokens already present; pass --print to issue, --rotate ROLE to rotate", file=sys.stderr)

    if args.print_tokens or created or rotated:
        print("Give each bot only its own role token. Do not commit these values.")
        for role in ROLES:
            if args.print_tokens or role in created or role in rotated:
                print(f"{role}={tokens[role]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
